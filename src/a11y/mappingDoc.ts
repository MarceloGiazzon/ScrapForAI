import { GUIDANCE_GROUPS, type GuidanceLang } from './platformGuidance.js';

/**
 * T7.7: renders docs/a11y-platform-mapping.md from the guidance table, so the document and what the reports print can never drift apart.
 * `npm run generate:a11y-doc` writes it; test/a11y-guidance.test.ts fails when the file on disk differs from this output.
 */

const SECTION: Record<GuidanceLang, { heading: string; rule: string; what: string; adjust: string; intro: string }> = {
  en: {
    heading: 'English',
    rule: 'Rules',
    what: 'What it means in the page',
    adjust: 'What to adjust in the GeneXus/NPDev model',
    intro: 'Each row groups the axe-core rules that call for the same kind of fix.',
  },
  pt: {
    heading: 'Português',
    rule: 'Regras',
    what: 'O que significa na página',
    adjust: 'O que ajustar no modelo GeneXus/NPDev',
    intro: 'Cada linha agrupa as regras do axe-core que pedem o mesmo tipo de correção.',
  },
  es: {
    heading: 'Español',
    rule: 'Reglas',
    what: 'Qué significa en la página',
    adjust: 'Qué ajustar en el modelo GeneXus/NPDev',
    intro: 'Cada fila agrupa las reglas de axe-core que piden el mismo tipo de corrección.',
  },
};

const cell = (text: string): string => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

export function renderMappingDoc(): string {
  const lines: string[] = [
    '<!-- GENERATED by `npm run generate:a11y-doc` from src/a11y/platformGuidance.ts. Do not edit by hand: edit the source and regenerate. -->',
    '',
    '# Accessibility rules -> what to adjust in a GeneXus/NPDev application',
    '',
    'When ScrapForAI audits a page (the `auditAccessibility` step, T7.4) it reports axe-core rule ids such as `color-contrast`. This table says what each',
    'rule means for the HTML the browser sees and where, in a GeneXus model, that HTML usually comes from. The run report (HTML/PDF, `en`/`pt`/`es`) and',
    'the evolution `CHANGES.md` print the same notes next to each violation.',
    '',
    '**This is orientation, not a recipe.** Property names change with the GeneXus version, and the GeneXus notes were not checked against a particular build',
    '(the NPDev ones were: see the last section). Confirm in your environment before changing a theme or a template that many screens share. Automated rules cover only part of',
    'WCAG: a page with no violations is not proven accessible (see also `keyboardWalk`, T7.6, which axe does not do).',
    '',
    '## How the audit is used',
    '',
    '- **Record**: `auditAccessibility { name, standard }` writes the violations of the page to `extracted[name]` and never fails (`failOn: "none"`, the default).',
    '- **Baseline**: an evolution snapshot taken with `accessibility: true` keeps, per screen, the violations of that build. A later audit with',
    '  `baseline: { screen }` reports only what is **new** and what was **fixed** since; `failOn: "new"` blocks only a regression. Legacy applications',
    '  have hundreds of old violations; the difference is what a team can act on.',
    '- **Standard**: `wcag2a`, `wcag2aa` (default), `wcag21aa`, `wcag22aa`. Best-practice rules of axe-core are not part of any of them.',
    '- **Limits**: only the audited frame is checked (iframe contents are not), and `target` is a CSS selector: the HTML, text and values of the element',
    '  are never read or stored.',
    '',
  ];

  for (const lang of ['en', 'pt', 'es'] as const) {
    const labels = SECTION[lang];
    lines.push(`## ${labels.heading}`, '', labels.intro, '');
    lines.push(`| ${labels.rule} | ${labels.what} | ${labels.adjust} |`, '| --- | --- | --- |');
    for (const group of GUIDANCE_GROUPS) {
      const text = group.text[lang];
      lines.push(`| **${cell(group.title[lang])}**<br>${group.rules.map((rule) => `\`${rule}\``).join(' ')} | ${cell(text.what)} | ${cell(text.platform)} |`);
    }
    lines.push('');
  }

  lines.push(
    '## NPDev applications',
    '',
    'NPDev is not GeneXus: "Label Position", "Textblock" or "Theme object" mean nothing in an NPDev workbench. For a target profile of `platform: npdev` the reports and `CHANGES.md`',
    'therefore print the note below instead of the GeneXus one. A note is written only after the finding was reproduced on a real NPDev build and traced to the generated HTML',
    '(2026-11-10, the WmsOffice workbenches: `label`, `select-name` and `color-contrast`; the audit found nothing else on the login page, the business UI home and four workbenches).',
    'A rule without such a note says it is **not verified for NPDev yet**.',
    '',
  );
  for (const lang of ['en', 'pt', 'es'] as const) {
    const labels = SECTION[lang];
    lines.push(`### ${labels.heading}`, '', `| ${labels.rule} | NPDev |`, '| --- | --- |');
    for (const group of GUIDANCE_GROUPS) {
      if (group.npdev) lines.push(`| **${cell(group.title[lang])}**<br>${group.rules.map((rule) => `\`${rule}\``).join(' ')} | ${cell(group.npdev[lang])} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}
